/** 最新一条日志（无条目时为 null） */
export const LATEST: ChangelogEntry | null = CHANGELOG[0] ?? null;

/**
 * 版本标识：日期 + 标题。
 * 带上标题是为了「同一天发两次版」也能区分（09-28 当天发过三条）；日期是等宽前缀，
 * 故 key 的字典序比较天然等价于时间先后。用途：记录玩家已读到哪一版。
 */
export function versionKey(e: ChangelogRef | null | undefined): string {
  return e ? `${e.date}|${e.title}` : '';
}

/**
 * 服务端版本是否比本页打包的版本新（即：本页是旧包，该提示刷新了）。
 *
 * 只比日期，**不**因为「同日但标题不同」就判定服务器更新：同一天发两次版时两个方向都是
 * 「标题不同」，无从判断谁在前——宁可漏报（同一天发版不提示）也不能误报（让所有人无意义地刷一次）。
 * 玩家是否读过最新日志由 versionKey 精确比对，不受此限制。
 */
export function isStaleBundle(
  server: ChangelogRef | null | undefined,
  bundled: ChangelogRef | null | undefined,
): boolean {
  if (!server || !bundled || !server.date) return false;
  return server.date > bundled.date;
}
